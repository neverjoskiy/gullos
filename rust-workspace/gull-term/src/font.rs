use std::collections::HashMap;
use std::fs;
use std::path::Path;

use ab_glyph::{Font, FontVec, PxScale, ScaleFont};

const SYSTEM_MONO_FONTS: &[&str] = &[
    "/usr/share/fonts/TTF/DejaVuSansMono.ttf",
    "/usr/share/fonts/TTF/NotoSansMono-Regular.ttf",
    "/usr/share/fonts/noto/NotoSansMono-Regular.ttf",
    "/usr/share/fonts/TTF/LiberationMono-Regular.ttf",
    "/usr/share/fonts/dejavu/DejaVuSansMono.ttf",
];

#[derive(Clone)]
pub struct RasterGlyph {
    pub width: usize,
    pub height: usize,
    pub offset_x: i32,
    pub offset_y: i32,
    pub alpha: Vec<u8>,
}

pub struct MonoFont {
    ttf: Option<FontVec>,
    px_size: f32,
    pub cell_w: usize,
    pub cell_h: usize,
    ascent: f32,
    cache: HashMap<(char, bool), RasterGlyph>,
}

impl MonoFont {
    pub fn load(px_size: f32) -> Self {
        let mut loaded_ttf = None;
        for candidate in SYSTEM_MONO_FONTS {
            if Path::new(candidate).is_file() {
                if let Ok(bytes) = fs::read(candidate) {
                    if let Ok(font) = FontVec::try_from_vec(bytes) {
                        loaded_ttf = Some(font);
                        break;
                    }
                }
            }
        }

        if let Some(ref font) = loaded_ttf {
            let scale = PxScale::from(px_size);
            let scaled = font.as_scaled(scale);
            let adv = scaled.h_advance(scaled.glyph_id('M')).ceil().max(8.0) as usize;
            let ascent = scaled.ascent();
            let descent = scaled.descent();
            let line_gap = scaled.line_gap();
            let height = (ascent - descent + line_gap + 2.0).ceil().max(16.0) as usize;

            Self {
                ttf: loaded_ttf,
                px_size,
                cell_w: adv,
                cell_h: height,
                ascent,
                cache: HashMap::with_capacity(256),
            }
        } else {
            // Built-in 8x16 crisp bitmap fallback so GullTerm always renders legibly
            Self {
                ttf: None,
                px_size: 16.0,
                cell_w: 9,
                cell_h: 18,
                ascent: 14.0,
                cache: HashMap::with_capacity(256),
            }
        }
    }

    pub fn glyph(&mut self, ch: char, bold: bool) -> &RasterGlyph {
        self.cache.entry((ch, bold)).or_insert_with(|| {
            if let Some(ref font) = self.ttf {
                rasterize_ttf_glyph(font, self.px_size, self.ascent, self.cell_w, self.cell_h, ch, bold)
            } else {
                rasterize_bitmap_fallback(ch, bold)
            }
        })
    }
}

fn rasterize_ttf_glyph(
    font: &FontVec,
    px_size: f32,
    ascent: f32,
    cell_w: usize,
    cell_h: usize,
    ch: char,
    bold: bool,
) -> RasterGlyph {
    if ch == ' ' || ch == '\0' {
        return RasterGlyph {
            width: 0,
            height: 0,
            offset_x: 0,
            offset_y: 0,
            alpha: Vec::new(),
        };
    }

    // Custom crisp box-drawing & block-element primitives for clean borders/prompts
    if let Some(custom) = rasterize_box_or_prompt_symbol(ch, cell_w, cell_h) {
        return custom;
    }

    let scale = PxScale::from(px_size);
    let glyph_id = font.glyph_id(ch);
    if glyph_id.0 == 0 && ch != '?' {
        return rasterize_bitmap_fallback(ch, bold);
    }

    let glyph = glyph_id.with_scale_and_position(scale, ab_glyph::point(0.0, ascent));
    if let Some(outlined) = font.outline_glyph(glyph) {
        let bounds = outlined.px_bounds();
        let w = bounds.width().ceil().max(1.0) as usize;
        let h = bounds.height().ceil().max(1.0) as usize;
        let stride_w = if bold { w + 1 } else { w };
        let mut alpha = vec![0u8; stride_w * h];

        outlined.draw(|x, y, cov| {
            let ux = x as usize;
            let uy = y as usize;
            if ux < w && uy < h {
                let v = (cov.clamp(0.0, 1.0) * 255.0).round() as u8;
                let idx = uy * stride_w + ux;
                alpha[idx] = alpha[idx].max(v);
                if bold && ux + 1 < stride_w {
                    let bidx = uy * stride_w + ux + 1;
                    alpha[bidx] = alpha[bidx].max(v.saturating_mul(3) / 4);
                }
            }
        });

        RasterGlyph {
            width: stride_w,
            height: h,
            offset_x: bounds.min.x.floor() as i32,
            offset_y: bounds.min.y.floor() as i32,
            alpha,
        }
    } else {
        RasterGlyph {
            width: 0,
            height: 0,
            offset_x: 0,
            offset_y: 0,
            alpha: Vec::new(),
        }
    }
}

fn rasterize_box_or_prompt_symbol(ch: char, cell_w: usize, cell_h: usize) -> Option<RasterGlyph> {
    let mut alpha = vec![0u8; cell_w * cell_h];
    let mid_x = cell_w / 2;
    let mid_y = cell_h / 2;

    match ch {
        '─' => {
            for x in 0..cell_w {
                alpha[mid_y * cell_w + x] = 255;
            }
        }
        '│' => {
            for y in 0..cell_h {
                alpha[y * cell_w + mid_x] = 255;
            }
        }
        '╭' | '┌' => {
            for x in mid_x..cell_w {
                alpha[mid_y * cell_w + x] = 255;
            }
            for y in mid_y..cell_h {
                alpha[y * cell_w + mid_x] = 255;
            }
        }
        '╰' | '└' => {
            for x in mid_x..cell_w {
                alpha[mid_y * cell_w + x] = 255;
            }
            for y in 0..=mid_y {
                alpha[y * cell_w + mid_x] = 255;
            }
        }
        '❯' => {
            let top = cell_h / 4;
            let bot = cell_h - top;
            let span = (bot - mid_y).max(1);
            for y in top..=bot {
                let dist = if y <= mid_y { y - top } else { bot - y };
                let x = (2 + (dist * (cell_w.saturating_sub(4))) / span).min(cell_w.saturating_sub(2));
                alpha[y * cell_w + x] = 255;
                if x + 1 < cell_w {
                    alpha[y * cell_w + x + 1] = 220;
                }
            }
        }
        '•' => {
            for dy in -1i32..=1 {
                for dx in -1i32..=1 {
                    let x = (mid_x as i32 + dx).clamp(0, cell_w as i32 - 1) as usize;
                    let y = (mid_y as i32 + dy).clamp(0, cell_h as i32 - 1) as usize;
                    alpha[y * cell_w + x] = 255;
                }
            }
        }
        '█' => {
            alpha.fill(255);
        }
        _ => return None,
    }

    Some(RasterGlyph {
        width: cell_w,
        height: cell_h,
        offset_x: 0,
        offset_y: 0,
        alpha,
    })
}

/// Complete built-in 8x16 VGA ASCII bitmap table (0x20..=0x7E) so `gull-term`
/// renders cleanly even if system fonts are temporarily absent.
fn rasterize_bitmap_fallback(ch: char, bold: bool) -> RasterGlyph {
    if let Some(sym) = rasterize_box_or_prompt_symbol(ch, 9, 18) {
        return sym;
    }

    let code = if (' '..='~').contains(&ch) {
        (ch as usize) - 0x20
    } else {
        ('?' as usize) - 0x20
    };

    let rows = &VGA_8X16[code];
    let w = 9usize;
    let h = 16usize;
    let mut alpha = vec![0u8; w * h];

    for (ry, &bits) in rows.iter().enumerate() {
        for rx in 0..8usize {
            if (bits & (0x80 >> rx)) != 0 {
                alpha[ry * w + rx] = 255;
                if bold && rx + 1 < w {
                    alpha[ry * w + rx + 1] = 200;
                }
            }
        }
    }

    RasterGlyph {
        width: w,
        height: h,
        offset_x: 0,
        offset_y: 1,
        alpha,
    }
}

